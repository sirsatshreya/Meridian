import crypto from 'crypto';
import { Agreement2, Agreement2Clause, TradeRequest, Organization } from '../types';

export function calculateAgreement2Hash(agreement: Omit<Agreement2, 'sha256Hash'>): string {
  const contentToHash = JSON.stringify({
    tradeRequestId: agreement.tradeRequestId,
    version: agreement.version,
    buyerOrgId: agreement.buyerOrgId,
    sellerOrgId: agreement.sellerOrgId,
    clauses: agreement.clauses.map((c) => ({
      id: c.id,
      number: c.number,
      title: c.title,
      content: c.content,
      status: c.status,
    })),
  });
  return crypto.createHash('sha256').update(contentToHash).digest('hex');
}


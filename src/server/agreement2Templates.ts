export function generateDefaultAgreement2(
  trade: TradeRequest,
  buyerOrg: Organization,
  sellerOrg: Organization
): Agreement2 {
  const now = new Date().toISOString();
  const clauses = buildDefaultAgreement2Clauses(trade, buyerOrg, sellerOrg);

  const base: Omit<Agreement2, 'sha256Hash'> = {
    id: `AGR2-${trade.id}`,
    tradeRequestId: trade.id,
    buyerOrgId: buyerOrg.id,
    buyerCompanyName: buyerOrg.legalName,
    sellerOrgId: sellerOrg.id,
    sellerCompanyName: sellerOrg.legalName,
    version: '0.1',
    status: 'TERMS_NEGOTIATING',
    clauses,
    signatures: {},
    legalReviewRequired: false,
    legalReviewCleared: true,
    createdAt: now,
    updatedAt: now,
  };

  const sha256Hash = calculateAgreement2Hash(base);
  return {
    ...base,
    sha256Hash,
  };
}
